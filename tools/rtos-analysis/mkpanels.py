#!/usr/bin/env python3
"""Turns emulator traces of a K1-family rtos image (one per simulated panel, PANEL=...) into the
panel table of nocry-rtos:   mkpanels.py tjc=run-tjc.log pj=... dc=... gc9503=... > rtos/panels_k1.h

From each trace it takes what the image did for that panel between starting its display thread
and switching the controller on: pixel clock, timing registers, and the power/reset/delay/serial
command sequence."""
import re, sys

NAMES = {'gc9503': ('gc9503cv_ue_480_800', 1), 'tjc': ('st7701_tjc_480_800', 3),
         'pj': ('st7701_9bit_spi_pj_480_800', 8), 'dc': ('st7701_9bit_spi_dc_480_800', 9)}

def parse(path):
    lines = [re.sub(r' +\[pc.*', '', l.rstrip('\n')) for l in open(path)]
    a = next(i for i, l in enumerate(lines) if 'thread enbale_fb_thread' in l)
    b = next(i for i, l in enumerate(lines) if i > a and l.startswith('W DPU+0x2014') and l.endswith('3e'))
    reg, ops = {}, []
    for l in lines[a:b]:
        m = re.match(r'W (\S+)\s+= (0x[0-9a-f]+)', l)
        if m:
            reg[m.group(1)] = int(m.group(2), 16)
        elif l.startswith('PIN  PC21'):
            ops.append('PWR(%s)' % l.split()[-1])
        elif l.startswith('PIN  PB29'):
            ops.append('RST(%s)' % l.split()[-1])
        elif l.startswith('# msleep('):
            ops.append('MS(%d)' % int(l[9:l.index(')')]))
        elif l.startswith('SPI'):
            for t in re.findall(r'cmd [0-9a-f]{2}:|<[0-9a-f]{2}|\?\S+ bits \S+|[0-9a-f]{2}\b', l[3:]):
                if t.startswith('cmd'):
                    ops.append('C(0x%s)' % t[4:6])
                elif t[0] not in '<?':
                    ops.append('D(0x%s)' % t)
    return reg, ops

print('/* SPDX-License-Identifier: GPL-2.0-or-later */')
print('/* Generated by tools/rtos-analysis/mkpanels.py from traces of the K1 firmware 1.3.3.5 rtos image. */')
order = ['gc9503', 'tjc', 'pj', 'dc']
got = dict(a.split('=', 1) for a in sys.argv[1:])
for k in order:
    reg, ops = parse(got[k])
    print('\nstatic const unsigned short script_%s[] = {' % k)
    line = '\t'
    for o in ops:
        if len(line) + len(o) > 96 or (o.startswith('C(') and len(line) > 8):
            print(line.rstrip()); line = '\t'
        line += o + ', '
    print(line + 'END')
    print('};')
    NAMES[k] += (reg,)
print('\nstatic const struct panel panels_k1[] = {')
for k in order:
    name, lcm, reg = NAMES[k]
    hs, hde, vs, vde = reg['DPU+0x9000'], reg['DPU+0x9008'], reg['DPU+0x9004'], reg['DPU+0x900c']
    xres, yres = (hde & 0xffff) - (hde >> 16), (vde & 0xffff) - (vde >> 16)
    print('\t{ "%s", %d, %d, %d, 0x%08x, { 0x%08x, 0x%08x, 0x%08x, 0x%08x, 0x%08x }, script_%s, detect_%s, %s },'
          % (name, lcm, xres, yres, reg['CPM+0x0064'], hs, vs, hde, vde, reg['DPU+0x9010'], k, k, 'gc9503_write' if k == 'gc9503' else 'link_write'))
print('};')
