#!/usr/bin/env python3
"""Makes font.h for nocry-banner: ASCII 32..126 of DejaVu Sans Mono (Bitstream Vera licence, free
to embed) as 12x24 one-bit glyphs. Run once; the result is committed.
usage: mkfont.py /path/to/DejaVuSansMono.ttf > font.h"""
import sys
from PIL import Image, ImageDraw, ImageFont
W, H = 12, 24
f = ImageFont.truetype(sys.argv[1], 20)
print("/* generated by mkfont.py from DejaVu Sans Mono, 20 px; %dx%d, one bit per pixel, MSB left */" % (W, H))
print("#define FONT_W %d\n#define FONT_H %d\nstatic const unsigned short font[95][%d] = {" % (W, H, H))
for c in range(32, 127):
    im = Image.new("L", (W, H), 0)
    ImageDraw.Draw(im).text((0, 0), chr(c), fill=255, font=f)
    rows = []
    for y in range(H):
        v = 0
        for x in range(W):
            v = v << 1 | (1 if im.getpixel((x, y)) >= 110 else 0)
        rows.append("0x%03x" % v)
    print("\t{ %s },\t/* %s */" % (", ".join(rows), chr(c) if c not in (92,) else "backslash"))
print("};")
